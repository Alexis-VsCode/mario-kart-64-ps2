static void copiar_letra(char c, unsigned char filas[FUENTE_5X7_FILAS])
{
    if (c >= 'a' && c <= 'z') {
        c = (char) (c - 'a' + 'A');
    }
    if (c >= PRIMER_CARACTER && c <= ULTIMO_CARACTER) {
        memcpy(&filas[1], fuente[c - PRIMER_CARACTER], FUENTE_5X7_FILAS - 1);
    }
}

int glifo_5x7(const char *c, unsigned char filas[FUENTE_5X7_FILAS])
{
    memset(filas, 0, FUENTE_5X7_FILAS);
    copiar_letra(*c, filas);
    return 1;
}

int escribir_linea_5x7(uint32_t *pixeles, int ancho_textura, int x0, int y0, const char *cadena, int columnas_max,
                       uint32_t color)
{
    int columna;

    for (columna = 0; *cadena != '\0' && columna < columnas_max; columna++) {
        unsigned char filas[FUENTE_5X7_FILAS];
        int fila, col;

        cadena += glifo_5x7(cadena, filas);
        for (fila = 0; fila < FUENTE_5X7_FILAS; fila++) {
            uint32_t *destino = &pixeles[(y0 - 1 + fila) * ancho_textura + x0 + columna * FUENTE_5X7_AVANCE];

            for (col = 0; col < FUENTE_5X7_ANCHO; col++) {
                if (filas[fila] & (0x10 >> col)) {
                    destino[col] = color;
                }
            }
        }
    }
    return columna;
}
